import random

def взять_карту():
    return random.randint(2, 11)

def показать_карты(игрок, дилер, скрыть_дилера=True):
    print(f"\nТвои карты: {игрок} | Сумма: {sum(игрок)}")
    if скрыть_дилера:
        print(f"Карты дилера: [{дилер[0]}, ?]")
    else:
        print(f"Карты дилера: {дилер} | Сумма: {sum(дилер)}")

def ход_игрока(игрок, дилер):
    while True:
        показать_карты(игрок, дилер)
        выбор = input("Взять карту (в) или остановиться (о)? ").lower()
        if выбор == 'в':
            карта = взять_карту()
            игрок.append(карта)
            print(f"Ты взял карту: {карта}")
            if sum(игрок) > 21:
                print("Перебор! Ты проиграл.")
                return False
        elif выбор == 'о':
            return True
        else:
            print("Введи 'в' или 'о'.")

def ход_дилера(дилер):
    while sum(дилер) < 17:
        карта = взять_карту()
        дилер.append(карта)
        print(f"Дилер взял карту: {карта}")
    return sum(дилер)

def определить_победителя(игрок, дилер):
    сумма_игрока = sum(игрок)
    сумма_дилера = sum(дилер)

    if сумма_дилера > 21:
        print("У дилера перебор. Ты выиграл!")
    elif сумма_игрока > сумма_дилера:
        print("Ты ближе к 21. Победа!")
    elif сумма_игрока < сумма_дилера:
        print("Дилер ближе к 21. Ты проиграл.")
    else:
        print("Ничья.")

def играть():
    print("Игра: 21 очко")

    игрок = [взять_карту(), взять_карту()]
    дилер = [взять_карту(), взять_карту()]

    if not ход_игрока(игрок, дилер):
        return

    print("\nХод дилера:")
    сумма_дилера = ход_дилера(дилер)

    показать_карты(игрок, дилер, скрыть_дилера=False)
    определить_победителя(игрок, дилер)
if __name__ == "__main__":
    играть()
